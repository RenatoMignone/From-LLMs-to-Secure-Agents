// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import sitemap from '@astrojs/sitemap';
import fs from 'node:fs';
import path from 'node:path';
import { discoverCanonicalChapters } from './scripts/discover-content.mjs';

const SITE_ORIGIN = 'https://renatomignone.github.io';
const BASE_URL = '/From-LLMs-to-Secure-Agents';

const { chapters, sections } = discoverCanonicalChapters();
const latestReview = chapters
  .map((chapter) => chapter.last_reviewed)
  .sort()
  .at(-1);
const lastModifiedByUrl = new Map([
  [`${SITE_ORIGIN}${BASE_URL}/`, latestReview],
  [`${SITE_ORIGIN}${BASE_URL}`, latestReview],
  ...chapters.map((chapter) => [chapter.canonicalUrl, chapter.last_reviewed]),
  ...sections.map((section) => [
    section.canonicalUrl,
    section.chapters.map((chapter) => chapter.last_reviewed).sort().at(-1),
  ]),
]);

// Read dynamic sidebar generated by the build pipeline
let sidebarItems = [];
const sidebarPath = path.resolve('./src/generated/sidebar.json');
if (fs.existsSync(sidebarPath)) {
  try {
    sidebarItems = JSON.parse(fs.readFileSync(sidebarPath, 'utf8'));
  } catch (e) {
    console.warn('Could not read sidebar.json:', e);
  }
}

export default defineConfig({
  site: 'https://renatomignone.github.io',
  base: '/From-LLMs-to-Secure-Agents',
  integrations: [
    starlight({
      title: 'From LLMs to Secure Agents',
      description: 'A visual, source-grounded engineering guide to understanding complete agentic AI architectures and learning how to secure them.',
      favicon: '/favicon.png',
      logo: {
        src: './src/assets/logo.png',
        alt: 'From LLMs to Secure Agents Robot Mascot',
      },
      social: [
        {
          icon: 'github',
          label: 'GitHub',
          href: 'https://github.com/RenatoMignone/From-LLMs-to-Secure-Agents',
        },
      ],
      customCss: [
        './src/styles/theme.css',
      ],
      components: {
        Header: './src/components/Header.astro',
        MobileMenuFooter: './src/components/MobileMenuFooter.astro',
        PageTitle: './src/components/PageTitle.astro',
        ThemeProvider: './src/components/ThemeProvider.astro',
        ThemeSelect: './src/components/ThemeSelect.astro',
      },
      head: [
        {
          tag: 'link',
          attrs: {
            rel: 'icon',
            type: 'image/png',
            sizes: '32x32',
            href: '/From-LLMs-to-Secure-Agents/favicon-32x32.png',
          },
        },
        {
          tag: 'link',
          attrs: {
            rel: 'icon',
            type: 'image/png',
            sizes: '16x16',
            href: '/From-LLMs-to-Secure-Agents/favicon-16x16.png',
          },
        },
        {
          tag: 'link',
          attrs: {
            rel: 'icon',
            type: 'image/png',
            href: '/From-LLMs-to-Secure-Agents/favicon.png',
          },
        },
        {
          tag: 'link',
          attrs: {
            rel: 'shortcut icon',
            href: '/From-LLMs-to-Secure-Agents/favicon.ico',
          },
        },
        {
          tag: 'link',
          attrs: {
            rel: 'apple-touch-icon',
            sizes: '180x180',
            href: '/From-LLMs-to-Secure-Agents/apple-touch-icon.png',
          },
        },
        {
          tag: 'meta',
          attrs: {
            name: 'theme-color',
            content: '#42948e',
          },
        },
        {
          tag: 'meta',
          attrs: {
            name: 'robots',
            content: 'index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1',
          },
        },
        {
          tag: 'meta',
          attrs: {
            property: 'og:site_name',
            content: 'From LLMs to Secure Agents',
          },
        },
        {
          tag: 'meta',
          attrs: {
            name: 'author',
            content: 'Renato Mignone',
          },
        },
      ],
      sidebar: sidebarItems,
    }),
    sitemap({
      serialize(item) {
        const lastReviewed = lastModifiedByUrl.get(item.url);
        return lastReviewed ? { ...item, lastmod: new Date(`${lastReviewed}T00:00:00Z`) } : item;
      },
    }),
  ],
});
